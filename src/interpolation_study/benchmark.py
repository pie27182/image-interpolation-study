"""Repeatable quality/runtime benchmark for library and scratch implementations."""

from __future__ import annotations

import csv
import statistics
import time
from pathlib import Path

import numpy as np
from PIL import Image

from .library import PILLOW_METHODS, resize_with_pillow
from .metrics import compare_images
from .resize import METHODS, resize


def _measure(resize_fn, image: np.ndarray, size: tuple[int, int], method: str,
             warmup: int, repeats: int) -> tuple[np.ndarray, list[float]]:
    for _ in range(warmup):
        resize_fn(image, size, method)
    timings: list[float] = []
    output: np.ndarray | None = None
    for _ in range(repeats):
        start = time.perf_counter()
        output = resize_fn(image, size, method)
        timings.append((time.perf_counter() - start) * 1000.0)
    assert output is not None
    return output, timings


def run_benchmark(
    image_path: str | Path,
    output_dir: str | Path,
    scale_factor: float = 2.0,
    degradation: str = "lanczos3",
    *,
    degradation_implementation: str = "scratch",
    warmup: int = 1,
    repeats: int = 5,
) -> list[dict[str, float | int | str]]:
    """Downsample a high-resolution reference, then reconstruct it repeatedly.

    By default the low-resolution input is generated by this project's own
    NumPy resampler. ``degradation_implementation="pillow"`` is available for
    controlled library-degradation experiments. All reconstruction methods
    receive the exact same low-resolution array. Pillow baselines are included
    separately; Mitchell and B-spline are scratch-only methods.
    """
    if not np.isfinite(scale_factor) or scale_factor <= 1.0:
        raise ValueError("scale_factor must be greater than 1")
    if degradation not in METHODS:
        raise ValueError(f"degradation must be one of {', '.join(METHODS)}")
    if degradation_implementation not in ("scratch", "pillow"):
        raise ValueError("degradation_implementation must be 'scratch' or 'pillow'")
    if degradation_implementation == "pillow" and degradation not in PILLOW_METHODS:
        raise ValueError(
            f"Pillow degradation does not provide {degradation!r}; "
            f"choose from {', '.join(PILLOW_METHODS)}"
        )
    if warmup < 0:
        raise ValueError("warmup must be non-negative")
    if repeats < 1:
        raise ValueError("repeats must be at least 1")

    output = Path(output_dir)
    output.mkdir(parents=True, exist_ok=True)
    with Image.open(image_path) as opened:
        original = np.asarray(opened.convert("RGB"), dtype=np.uint8)

    height, width = original.shape[:2]
    low_size = (max(1, round(width / scale_factor)), max(1, round(height / scale_factor)))
    if degradation_implementation == "scratch":
        low_res = resize(original, low_size, degradation, antialias=True)
    else:
        low_res = resize_with_pillow(original, low_size, degradation)
    low_res_u8 = np.clip(np.rint(low_res), 0, 255).astype(np.uint8)
    Image.fromarray(low_res_u8).save(output / "low_resolution_input.png")

    rows: list[dict[str, float | int | str]] = []
    experiments = (
        ("pillow", PILLOW_METHODS, lambda arr, size, method: resize_with_pillow(arr, size, method)),
        ("scratch", METHODS, lambda arr, size, method: resize(arr, size, method)),
    )
    for implementation, methods, resize_fn in experiments:
        for method in methods:
            result, timings = _measure(resize_fn, low_res_u8, (width, height), method, warmup, repeats)
            result_u8 = np.clip(np.rint(result), 0, 255).astype(np.uint8)
            Image.fromarray(result_u8).save(output / f"{implementation}_{method}.png")
            metrics = compare_images(original, result_u8)
            rows.append({
                "implementation": implementation,
                "method": method,
                "time_median_ms": statistics.median(timings),
                "time_mean_ms": statistics.fmean(timings),
                "time_stdev_ms": statistics.stdev(timings) if len(timings) > 1 else 0.0,
                "time_min_ms": min(timings),
                "repeats": repeats,
                "warmup": warmup,
                "mse": metrics["mse"],
                "psnr_db": metrics["psnr"],
                "ssim_uniform": metrics["ssim"],
                "source_width": width,
                "source_height": height,
                "low_width": low_size[0],
                "low_height": low_size[1],
                "scale_factor": scale_factor,
                "degradation_filter": degradation,
                "degradation_implementation": degradation_implementation,
                "scratch_coordinate_mode": "half_pixel",
                "scratch_boundary": "clamp",
                "scratch_antialias": True,
                "metric_data_range": 255.0,
                "ssim_window": 7,
            })

    with (output / "results.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    return rows
